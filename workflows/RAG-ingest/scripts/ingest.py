def _extract_text(record: Any) -> str:
    if isinstance(record, str):
        return record
    if isinstance(record, Mapping):
        return str(record.get("text") or record.get("content") or "")
    return str(getattr(record, "text", "") or "")


def normalize_text(text: str) -> str:
    text = re.sub(r"/uniF[0-9A-Fa-f]{3,5}", " ", text or "")
    text = re.sub(r"[\u200b-\u200f\ufeff]", "", text)
    lines = []
    for raw in text.splitlines():
        line = re.sub(r"\s+", " ", raw).strip()
        if line and not re.fullmatch(r"\d{1,4}", line):
            lines.append(line)
    return "\n".join(lines).strip()


def _line_stats(text: str) -> dict[str, float]:
    lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
    if not lines:
        return {"line_count": 0, "short_line_ratio": 0.0, "one_token_line_ratio": 0.0, "year_line_ratio": 0.0}
    return {
        "line_count": len(lines),
        "short_line_ratio": sum(len(ln) < 35 for ln in lines) / len(lines),
        "one_token_line_ratio": sum(len(TOKEN_RE.findall(ln)) <= 1 for ln in lines) / len(lines),
        "year_line_ratio": sum(bool(YEAR_RE.fullmatch(ln)) for ln in lines) / len(lines),
    }


def chunk_features(text: str) -> dict[str, Any]:
    text = normalize_text(text)
    tokens = TOKEN_RE.findall(text)
    chars = max(len(text), 1)
    alpha = sum(ch.isalpha() for ch in text)
    numeric = sum(ch.isdigit() for ch in text)
    upper = sum(ch.isupper() for ch in text)
    lines = _line_stats(text)
    features = {
        "token_count": len(tokens),
        "sentence_count": len(SENTENCE_RE.findall(text)),
        "alpha_ratio": alpha / chars,
        "numeric_ratio": numeric / chars,
        "upper_ratio": upper / chars,
        "doi_count": len(DOI_RE.findall(text)),
        "email_count": len(EMAIL_RE.findall(text)),
        "orcid_count": len(ORCID_RE.findall(text)),
        "url_count": len(URL_RE.findall(text)),
        "kv_count": len(KV_RE.findall(text)),
        "pipe_count": text.count("|"),
        "toc_dot_count": len(TOC_DOTS_RE.findall(text)),
        "caption_like": bool(CAPTION_RE.search(text)),
        "table_metric_count": len(TABLE_METRIC_RE.findall(text)),
        "science_term_count": len(SCIENCE_TERM_RE.findall(text)),
        "formal_definition_count": len(FORMAL_DEFINITION_RE.findall(text)),
        "comma_count": text.count(","),
        "semicolon_count": text.count(";"),
        "long_token_count": sum(len(tok) > 80 for tok in tokens),
    }
    features.update(lines)
    return features


def _headings(record: Any) -> list[str]:
    if isinstance(record, Mapping):
        meta = record.get("meta") or {}
        value = meta.get("headings") or record.get("headings") or []
    else:
        value = getattr(record, "headings", []) or []
    if isinstance(value, str):
        return [value]
    return [str(x) for x in value if x]


def _in_drop_section(record: Any) -> bool:
    return any(DROP_SECTION_RE.fullmatch(h.strip()) for h in _headings(record))


def _compact_scientific(f: Mapping[str, Any]) -> bool:
    return (
        f["token_count"] >= 20
        and (f["science_term_count"] >= 2 or f.get("formal_definition_count", 0) >= 1)
        and f["alpha_ratio"] >= 0.58
        and f["email_count"] == 0
        and f["orcid_count"] == 0
    )


def _looks_bibliographic(text: str, f: Mapping[str, Any]) -> bool:
    hits = 0
    hits += 1 if BIB_AUTHOR_RE.search(text) else 0
    hits += 1 if BIB_VOLUME_RE.search(text) else 0
    hits += 1 if re.search(r"\b(et al\.|pp\.|vol\.|doi|pubmed|crossref|journal|elsevier|springer|wiley)\b", text, re.I) else 0
    hits += 1 if f["doi_count"] or f["url_count"] else 0
    return hits >= 3 and f["token_count"] < 190 and f["sentence_count"] <= 4


def _looks_supplement_notice(text: str, f: Mapping[str, Any]) -> bool:
    low = text.lower()
    if "supplementary" not in low and "supporting information" not in low:
        return False
    if f["token_count"] < 90:
        return True
    notice_terms = ("available online", "available at", "the following supporting information", "supplemental material")
    return any(term in low for term in notice_terms) and f["sentence_count"] <= 3


def _looks_boilerplate(text: str, f: Mapping[str, Any]) -> bool:
    low = text.lower()
    if (f["email_count"] or f["orcid_count"] > 1) and f["token_count"] < 150:
        return True
    if "corresponding author" in low and (EMAIL_RE.search(text) or "phone" in low):
        return True
    if "authors declare" in low and ("competing" in low or "conflict" in low):
        return f["token_count"] < 140
    if "all authors have given approval" in low:
        return True
    if all(word in low for word in ("received", "accepted", "published")):
        return f["token_count"] < 110
    if "creative commons" in low or "unless otherwise stated in a credit line" in low:
        return f["token_count"] < 140
    if "publisher's note" in low or "springer nature remains neutral" in low:
        return True
    return _looks_supplement_notice(text, f)


def _looks_table_debris(text: str, f: Mapping[str, Any]) -> bool:
    if f["sentence_count"] >= 3 and f["science_term_count"] >= 2:
        return False
    if f["pipe_count"] >= 2 and f["sentence_count"] < 3:
        return True
    if f["kv_count"] >= 4 and f["sentence_count"] < 3:
        return True
    if f["caption_like"] and f["short_line_ratio"] > 0.65 and (f["numeric_ratio"] > 0.10 or f["upper_ratio"] > 0.12):
        return True
    if f["table_metric_count"] >= 4 and f["numeric_ratio"] > 0.14 and f["sentence_count"] <= 2:
        return True
    if f["short_line_ratio"] > 0.45 and f["numeric_ratio"] > 0.18 and f["sentence_count"] < 2:
        return True
    return False


def drop_reason(record: Any) -> str | None:
    text = normalize_text(_extract_text(record))
    if not text:
        return "empty"
    if _in_drop_section(record):
        return "drop_section_heading"

    f = chunk_features(text)
    compact_scientific = _compact_scientific(f)
    definition_like = f.get("formal_definition_count", 0) >= 1 and f["token_count"] >= 15 and f["alpha_ratio"] >= 0.55

    if f["token_count"] < 12:
        return "too_short"
    if f["token_count"] < 20 and not compact_scientific and not definition_like:
        return "too_short"
    if f["sentence_count"] == 0 and f["token_count"] < 60:
        if (compact_scientific or definition_like) and not f["caption_like"] and f["numeric_ratio"] <= 0.22:
            return None
        if f["numeric_ratio"] > 0.12 or f["email_count"] or f["orcid_count"]:
            return "numeric_or_contact_fragment"
        if f["comma_count"] >= 4 or f["caption_like"] or f["pipe_count"]:
            return "fragment_without_sentence"
    if f["sentence_count"] <= 1 and f["token_count"] < 30 and not compact_scientific and not definition_like:
        return "short_single_sentence"
    if _looks_boilerplate(text, f):
        return "boilerplate_or_notice"
    if _looks_bibliographic(text, f):
        return "bibliographic_fragment"
    if f["toc_dot_count"] >= 2 or (f["toc_dot_count"] and f["numeric_ratio"] > 0.12):
        return "table_of_contents"
    if f["caption_like"] and (f["sentence_count"] <= 1 or f["token_count"] < 45) and not compact_scientific:
        return "orphan_caption"
    if _looks_table_debris(text, f):
        return "table_debris"
    if f["one_token_line_ratio"] > 0.30 and f["year_line_ratio"] > 0.10 and f["sentence_count"] < 2:
        return "reference_like_line_list"
    if f["alpha_ratio"] < 0.50 and f["numeric_ratio"] > 0.28 and f["sentence_count"] < 2:
        return "numeric_fragment"
    if f["long_token_count"] > 2 and f["token_count"] < 120:
        return "encoding_or_url_fragment"
    return None


def should_drop_text(text: str) -> bool:
    return drop_reason(text) is not None


def should_keep_chunk(record: Any) -> bool:
    return drop_reason(record) is None


