def merge_rows(a: dict[str, Any], b: dict[str, Any]) -> dict[str, Any]:
    merged = dict(a)
    merged["chunk_id"] = f"{a['chunk_id']}__merge__{b['chunk_id']}"
    merged["text"] = (a.get("text", "").rstrip() + "\n\n" + b.get("text", "").lstrip()).strip()
    merged["page_numbers"] = _dedupe_sorted(list(a.get("page_numbers", [])) + list(b.get("page_numbers", [])))
    merged["headings"] = _dedupe_sorted(list(a.get("headings", [])) + list(b.get("headings", [])))
    merged["content_type"] = classify_content_type(merged["text"], merged["headings"])
    merged["quality_flags"] = get_quality_flags(merged["text"], merged["content_type"], merged["headings"])
    merged["rag_fitness_score"] = score_rag_fitness(merged["text"], merged["content_type"], merged["quality_flags"])
    merged["boundary_flags"] = {
        "starts_lowercase": starts_lowercase(merged["text"]),
        "ends_incomplete": is_incomplete_end(merged["text"]),
        "has_complete_sentence": sentence_count(merged["text"]) > 0,
    }
    merged["token_count"] = token_count(merged["text"])
    merged["sentence_count"] = sentence_count(merged["text"])
    merged["source_chunk_ids"] = list(dict.fromkeys(a.get("source_chunk_ids", [a["chunk_id"]]) + b.get("source_chunk_ids", [b["chunk_id"]])))
    merged["merge_reason"] = "neighbor_boundary_repair"
    merged["meta"] = dict(merged.get("meta") or {})
    merged["meta"].update({
        "page_numbers": merged["page_numbers"],
        "headings": merged["headings"],
        "content_type": merged["content_type"],
        "source_chunk_ids": merged["source_chunk_ids"],
    })
    return merged


def postprocess_rows(rows: list[dict[str, Any]], min_merge_tokens: int, max_merge_tokens: int) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    merged: list[dict[str, Any]] = []
    i = 0
    while i < len(rows):
        row = rows[i]
        should_try_merge = (
            (row.get("token_count", 0) < min_merge_tokens or row.get("boundary_flags", {}).get("ends_incomplete"))
            and i + 1 < len(rows)
            and row.get("content_type") not in {"reference"}
        )
        if should_try_merge:
            candidate = merge_rows(row, rows[i + 1])
            if candidate.get("token_count", 0) <= max_merge_tokens and candidate.get("rag_fitness_score", 0) >= row.get("rag_fitness_score", 0):
                merged.append(candidate)
                i += 2
                continue
        merged.append(row)
        i += 1

    kept: list[dict[str, Any]] = []
    quarantined: list[dict[str, Any]] = []
    for row in merged:
        reason = drop_reason(row)
        if reason is None:
            kept.append(row)
        else:
            q = dict(row)
            q["quarantine_reason"] = reason
            q["quarantined_at"] = utc_now()
            quarantined.append(q)
    return kept, quarantined


def update_qa(
    qa: dict[str, Any],
    *,
    pdf_name: str,
    original: int,
    kept: list[dict[str, Any]],
    quarantine: list[dict[str, Any]],
    source_info: dict[str, Any],
    error: str | None = None,
) -> None:
    totals = qa["totals"]
    totals["documents_processed"] += 1
    if error:
        totals["documents_failed"] += 1
    totals["original_chunks"] += original
    totals["kept_chunks"] += len(kept)
    totals["quarantined_chunks"] += len(quarantine)
    totals["ingestion_strategies"].update([source_info.get("ingestion_strategy") or "unassigned"])
    for row in kept:
        totals["quality_flags"].update(row.get("quality_flags", []))
        totals["content_types"].update([row.get("content_type")])
        totals["rag_fitness_scores"].append(row.get("rag_fitness_score", 0))
    for row in quarantine:
        totals["quarantine_reasons"].update([row.get("quarantine_reason", "unknown")])

    qa["documents"][pdf_name] = {
        "error": error,
        "original_chunks": original,
        "kept_chunks": len(kept),
        "quarantined_chunks": len(quarantine),
        "source_relative_path": source_info.get("source_relative_path"),
        "ingestion_strategy": source_info.get("ingestion_strategy"),
        "ingestion_strategy_name": source_info.get("ingestion_strategy_name"),
        "strategy_is_assigned": source_info.get("strategy_is_assigned"),
        "kept_quality_flags": dict(Counter(flag for row in kept for flag in row.get("quality_flags", []))),
        "content_types": dict(Counter(row.get("content_type") for row in kept)),
        "quarantine_reasons": dict(Counter(row.get("quarantine_reason", "unknown") for row in quarantine)),
        "high_risk_chunks": sum(row.get("rag_fitness_score", 0) < 0.55 for row in kept),
        "incomplete_boundary_chunks": sum(row.get("boundary_flags", {}).get("ends_incomplete") for row in kept),
    }


def finalize_qa(qa: dict[str, Any], major_change_count: int) -> dict[str, Any]:
    totals = qa["totals"]
    scores = totals.pop("rag_fitness_scores", [])
    totals["quality_flags"] = dict(totals["quality_flags"])
    totals["content_types"] = dict(totals["content_types"])
    totals["quarantine_reasons"] = dict(totals["quarantine_reasons"])
    totals["ingestion_strategies"] = dict(totals["ingestion_strategies"])
    totals["major_change_records"] = major_change_count
    kept = max(totals.get("kept_chunks", 0), 1)
    totals["high_risk_chunk_ratio"] = round(
        sum(doc.get("high_risk_chunks", 0) for doc in qa["documents"].values()) / kept,
        6,
    )
    totals["incomplete_boundary_ratio"] = round(
        sum(doc.get("incomplete_boundary_chunks", 0) for doc in qa["documents"].values()) / kept,
        6,
    )
    totals["unassigned_strategy_documents"] = sum(
        1 for doc in qa["documents"].values() if not doc.get("strategy_is_assigned")
    )
    if scores:
        totals["rag_fitness"] = {
            "mean": round(statistics.mean(scores), 4),
            "median": round(statistics.median(scores), 4),
            "min": round(min(scores), 4),
            "max": round(max(scores), 4),
        }
    else:
        totals["rag_fitness"] = {"mean": None, "median": None, "min": None, "max": None}
    qa["finalized_at"] = utc_now()
    return qa


