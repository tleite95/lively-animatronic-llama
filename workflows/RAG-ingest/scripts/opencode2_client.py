def emit(depth: int, icon: str, text: str) -> None:
    prefix = "\u2502  " * depth  # "│  " per depth level
    for i, line in enumerate(text.splitlines() or [""]):
        marker = icon if i == 0 else "  "
        print(f"{prefix}{marker} {line}", flush=True)


def fmt_tokens(tokens: dict) -> str:
    cache = tokens.get("cache", {}) or {}
    return (
        f"in={tokens.get('input', 0)} out={tokens.get('output', 0)} "
        f"reasoning={tokens.get('reasoning', 0)} "
        f"cache(read={cache.get('read', 0)},write={cache.get('write', 0)})"
    )


@dataclass
class SessionNode:
    session_id: str
    parent_id: Optional[str]
    depth: int
    label: str
    known_message_ids: set = field(default_factory=set)
    part_state: dict = field(default_factory=dict)   # (message_id, idx) -> {"status": ..., "len": ...}
    spawned_children: set = field(default_factory=set)  # tool part ids already resolved to a child session
    claimed_child_ids: set = field(default_factory=set)
    last_status_line: Optional[str] = None
    model_ref: Optional[dict] = None


class Monitor:
    """Polls (SSE-nudged) session + message state and renders a live tree."""

    def __init__(self, client: OpenCodeClient, catalog: ModelCatalog, quiet: bool = False):
        self.client = client
        self.catalog = catalog
        self.quiet = quiet
        self.nodes: dict[str, SessionNode] = {}

    def run(self, root_session_id: str, root_agent_label: str, wait_timeout: float) -> str:
        self.nodes[root_session_id] = SessionNode(
            session_id=root_session_id, parent_id=None, depth=0, label=root_agent_label
        )

        waker = SSEWaker(self.client)
        waker.start()

        wait_error: list[Exception] = []
        wait_done = threading.Event()

        def _wait_target():
            try:
                self.client.wait(root_session_id, timeout=wait_timeout)
            except Exception as e:  # noqa: BLE001
                wait_error.append(e)
            finally:
                wait_done.set()

        wait_thread = threading.Thread(target=_wait_target, daemon=True)
        wait_thread.start()

        grace_passes_remaining = 2  # extra syncs after root goes idle, to catch trailing sub-agent output
        try:
            while True:
                woke_by_event = waker.wait(timeout=POLL_FALLBACK_INTERVAL)
                self._sync_all()
                if wait_done.is_set():
                    if grace_passes_remaining <= 0:
                        break
                    grace_passes_remaining -= 1
        finally:
            waker.stop()

        if wait_error:
            raise wait_error[0]

        return self._final_text(root_session_id)

    # -- syncing ----------------------------------------------------------

    def _sync_all(self) -> None:
        # iterate over a snapshot since _sync_node may add new nodes (children)
        for node in list(self.nodes.values()):
            self._sync_node(node)

    def _sync_node(self, node: SessionNode) -> None:
        try:
            info = self.client.get_session(node.session_id)
        except requests.exceptions.RequestException:
            return
        node.model_ref = info.get("model")

        if not self.quiet:
            self._maybe_print_status(node, info)

        try:
            messages = self.client.get_messages(node.session_id, order="asc")
        except requests.exceptions.RequestException:
            return

        for message in messages:
            self._handle_message(node, message)

    def _maybe_print_status(self, node: SessionNode, info: dict) -> None:
        tokens = info.get("tokens") or {}
        cost = info.get("cost")
        ctx_limit = self.catalog.context_limit(node.model_ref)
        ctx_used = tokens.get("input", 0) + (tokens.get("cache", {}) or {}).get("read", 0)
        pct = f"{(ctx_used / ctx_limit * 100):.1f}%" if ctx_limit else "?"
        line = (
            f"[{node.label}] tokens: {fmt_tokens(tokens)} | "
            f"context: {ctx_used}/{ctx_limit or '?'} ({pct}) | cost: ${cost or 0:.4f}"
        )
        if line != node.last_status_line:
            emit(node.depth, "\U0001F4CA", line)  # 📊
            node.last_status_line = line

    def _handle_message(self, node: SessionNode, message: dict) -> None:
        msg_id = message.get("id")
        msg_type = message.get("type")
        is_new = msg_id not in node.known_message_ids

        if msg_type == "assistant":
            self._handle_assistant_content(node, message)
            return  # assistant messages update incrementally; header not needed

        if not is_new:
            return
        node.known_message_ids.add(msg_id)

        if msg_type == "skill":
            emit(node.depth, "\U0001F4CE", f"skill activated: {message.get('name', message.get('skill'))}")
        elif msg_type == "agent-switched":
            emit(node.depth, "\U0001F501", f"agent switched -> {message.get('agent')}")
        elif msg_type == "model-switched":
            m = message.get("model", {})
            emit(node.depth, "\U0001F501", f"model switched -> {m.get('providerID')}/{m.get('id')}")
        elif msg_type == "user":
            text = (message.get("text") or "").strip()
            if text:
                preview = text if len(text) <= 300 else text[:300] + "…"
                emit(node.depth, "\U0001F464", f"user: {preview}")
        elif msg_type == "compaction":
            emit(node.depth, "\U0001F5DC", f"compaction {message.get('status')} ({message.get('reason')})")
        # "synthetic" / "system" messages are intentionally not printed (low signal)

    def _handle_assistant_content(self, node: SessionNode, message: dict) -> None:
        msg_id = message.get("id")
        node.known_message_ids.add(msg_id)
        content = message.get("content") or []

        for idx, part in enumerate(content):
            key = (msg_id, idx)
            ptype = part.get("type")

            if ptype == "text":
                self._render_growing_text(node, key, part.get("text", ""), icon="\U0001F4AC")  # 💬
            elif ptype == "reasoning":
                self._render_growing_text(node, key, part.get("text", ""), icon="\U0001F9E0")  # 🧠
            elif ptype == "tool":
                self._handle_tool_part(node, message, key, part)

    def _render_growing_text(self, node: SessionNode, key: tuple, text: str, icon: str) -> None:
        prev = node.part_state.get(key, {})
        prev_len = prev.get("len", 0)
        if len(text) <= prev_len:
            return
        delta = text[prev_len:][:TEXT_PREVIEW_CHARS]
        emit(node.depth, icon, delta)
        node.part_state[key] = {"len": len(text)}

    def _handle_tool_part(self, node: SessionNode, message: dict, key: tuple, part: dict) -> None:
        name = part.get("name", "?")
        state = part.get("state") or {}
        status = state.get("status")
        prev = node.part_state.get(key, {})

        if prev.get("status") == status:
            return  # no change to report
        node.part_state[key] = {**prev, "status": status}

        if status in ("streaming", "running"):
            tool_input = state.get("input")
            input_preview = _short_repr(tool_input)
            icon = "\U0001F916" if name == "task" else "\U0001F527"  # 🤖 for subagent, 🔧 otherwise
            emit(node.depth, icon, f"tool: {name} ({status}) input={input_preview}")
        elif status == "completed":
            output_preview = _short_repr(_tool_content_text(state.get("content")))
            emit(node.depth, "\u2705", f"tool: {name} completed -> {output_preview}")
        elif status == "error":
            err = (state.get("error") or {}).get("message", "unknown error")
            emit(node.depth, "\u274C", f"tool: {name} error -> {err}")

        if name == "task" and status in ("running", "completed") and key not in node.spawned_children:
            self._discover_child_session(node, key)

    def _discover_child_session(self, node: SessionNode, tool_key: tuple) -> None:
        node.spawned_children.add(tool_key)
        try:
            all_sessions = self.client.list_sessions()
        except requests.exceptions.RequestException:
            return
        candidates = [
            s for s in all_sessions
            if s.get("parentID") == node.session_id
            and s.get("id") not in self.nodes
            and s.get("id") not in node.claimed_child_ids
        ]
        if not candidates:
            return
        candidates.sort(key=lambda s: (s.get("time") or {}).get("created", 0))
        child = candidates[0]
        child_id = child["id"]
        node.claimed_child_ids.add(child_id)
        label = f"subagent:{child.get('agent', '?')}"
        self.nodes[child_id] = SessionNode(
            session_id=child_id, parent_id=node.session_id, depth=node.depth + 1, label=label
        )
        emit(node.depth, "\U0001F440", f"-> spawned child session {child_id} ({label})")

    def _final_text(self, session_id: str) -> str:
        try:
            messages = self.client.get_messages(session_id, order="desc", limit=20)
        except requests.exceptions.RequestException:
            return ""
        for message in messages:
            if message.get("type") == "assistant":
                parts = [
                    p.get("text", "") for p in (message.get("content") or []) if p.get("type") == "text"
                ]
                if parts:
                    return "\n".join(parts)
        return ""


def _short_repr(value: Any, limit: int = 200) -> str:
    text = value if isinstance(value, str) else str(value)
    text = text.replace("\n", " ")
    return text if len(text) <= limit else text[:limit] + "…"


def _tool_content_text(content: Any) -> str:
    if not isinstance(content, list):
        return ""
    parts = [c.get("text", "") for c in content if isinstance(c, dict) and c.get("type") == "text"]
    return " ".join(parts)


