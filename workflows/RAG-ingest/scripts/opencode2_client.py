#!/usr/bin/env python3

"""
---
Generated by Claude.ai Sonnet 5 (Medium effort)
---

Run a prompt against a locally running OpenCode 2 server (HttpApi v2), with a
specific agent, skill, and provider/model — and stream live visibility into
what the agent is doing: thinking (reasoning), tool calls, skill use,
sub-agent invocations, and token / context-window usage, rendered as an
indented tree so sub-agent activity nests under the tool call that spawned it.

Requires OpenCode 2 running locally, e.g.:

    opencode2 serve --port 4096

Docs: https://opencode.ai/v2/docs/api

Usage:
    python opencode_run.py \
        --prompt "Refactor this function for clarity" \
        --agent build \
        --skill code-review \
        --provider anthropic \
        --model claude-sonnet-5 \
        --directory /path/to/your/project

Add --quiet to suppress the live tree and just print the final answer
(useful for scripting / piping).

--- Design notes / known assumptions ---

The v2 HttpApi is marked "experimental" and its SSE event payload shape
(GET /api/event) isn't documented beyond the outer envelope
{id, event, data}. Rather than depend on parsing that payload precisely,
this script uses the event stream only as a low-latency "something
changed, go re-sync" signal (falling back to polling on a fixed interval
regardless, so it degrades gracefully if SSE payload parsing ever fails
or the stream drops). The actual rendering is always driven by re-reading
GET /api/session/{id} and GET /api/session/{id}/message, so what you see
is always ground truth from the API, just possibly ~1 poll-interval late
if SSE didn't wake us early.

Sub-agent discovery: the model invokes sub-agents via a "task" tool.
There is no documented field linking a task-tool call directly to the
child session it spawns, so this script infers it heuristically: after a
"task" tool call appears, it lists all sessions and claims the newest
not-yet-claimed session whose parentID matches the current session. This
works well for the common case of sequential sub-agent calls; if an agent
fires many sub-agents in tight parallel, attribution to the *correct*
task call may be approximate (though every child session is still found
and rendered).
"""

import argparse
import os
import queue
import sys
import threading
import time
from dataclasses import dataclass, field
from typing import Any, Optional

import requests


DEFAULT_BASE_URL = "http://localhost:4096"
POLL_FALLBACK_INTERVAL = 1.5  # seconds; used when no SSE event wakes us up
TEXT_PREVIEW_CHARS = 4000     # cap how much of a single delta we print at once


# --------------------------------------------------------------------------
# HTTP client
# --------------------------------------------------------------------------

class OpenCodeClient:
    def __init__(
        self,
        base_url: str = DEFAULT_BASE_URL,
        username: str | None = None,
        password: str | None = None,
    ):
        self.base_url = base_url.rstrip("/")
        self.session = requests.Session()
        password = password or os.environ.get("OPENCODE_PASSWORD") or os.environ.get("OPENCODE_SERVER_PASSWORD")
        username = username or os.environ.get("OPENCODE_SERVER_USERNAME") or "opencode"
        if password:
            self.session.auth = requests.auth.HTTPBasicAuth(username, password)

    def _url(self, path: str) -> str:
        return f"{self.base_url}{path}"

    def _check_auth_error(self, resp: requests.Response) -> None:
        if resp.status_code == 401:
            raise RuntimeError(
                "OpenCode server rejected the request (401 Unauthorized). "
                "The server requires HTTP Basic Auth — pass --password (and --username "
                "if you changed it), or set OPENCODE_PASSWORD / OPENCODE_SERVER_PASSWORD. "
                "opencode2 prints the auto-generated password to its own stdout/log at "
                "startup if you didn't set one explicitly."
            )

    # -- health / misc -------------------------------------------------

    def health(self) -> dict:
        resp = self.session.get(self._url("/api/health"))
        self._check_auth_error(resp)
        resp.raise_for_status()
        return resp.json()

    # -- session lifecycle ----------------------------------------------

    def create_session(
        self,
        directory: str,
        agent: str | None = None,
        title: str | None = None,
        provider_id: str | None = None,
        model_id: str | None = None,
        variant: str | None = None,
    ) -> str:
        body: dict[str, Any] = {"location": {"directory": directory}}
        if agent:
            body["agent"] = agent
        if title:
            body["title"] = title
        if provider_id or model_id:
            if not (provider_id and model_id):
                raise ValueError("Both provider and model must be given together")
            model_ref = {"id": model_id, "providerID": provider_id}
            if variant:
                model_ref["variant"] = variant
            body["model"] = model_ref

        resp = self.session.post(self._url("/api/session"), json=body)
        self._check_auth_error(resp)
        resp.raise_for_status()
        return resp.json()["data"]["id"]

    def get_session(self, session_id: str) -> dict:
        resp = self.session.get(self._url(f"/api/session/{session_id}"))
        self._check_auth_error(resp)
        resp.raise_for_status()
        return resp.json()["data"]

    def list_sessions(self) -> list[dict]:
        resp = self.session.get(self._url("/api/session"))
        self._check_auth_error(resp)
        resp.raise_for_status()
        return resp.json()["data"]

    def switch_agent(self, session_id: str, agent: str) -> None:
        resp = self.session.post(
            self._url(f"/api/session/{session_id}/agent"), json={"agent": agent}
        )
        self._check_auth_error(resp)
        resp.raise_for_status()

    def switch_model(self, session_id: str, provider_id: str, model_id: str, variant: str | None = None) -> None:
        model_ref = {"id": model_id, "providerID": provider_id}
        if variant:
            model_ref["variant"] = variant
        resp = self.session.post(
            self._url(f"/api/session/{session_id}/model"), json={"model": model_ref}
        )
        self._check_auth_error(resp)
        resp.raise_for_status()

    def activate_skill(self, session_id: str, skill: str, resume: bool = False) -> None:
        resp = self.session.post(
            self._url(f"/api/session/{session_id}/skill"),
            json={"skill": skill, "resume": resume},
        )
        self._check_auth_error(resp)
        resp.raise_for_status()

    def send_prompt(self, session_id: str, text: str, resume: bool = True) -> dict:
        resp = self.session.post(
            self._url(f"/api/session/{session_id}/prompt"),
            json={"text": text, "resume": resume},
        )
        self._check_auth_error(resp)
        resp.raise_for_status()
        return resp.json()["data"]

    def wait(self, session_id: str, timeout: float = 600.0) -> None:
        """Blocks (server-side) until the session's agent loop goes idle."""
        resp = self.session.post(
            self._url(f"/api/session/{session_id}/wait"),
            timeout=timeout + 30,
        )
        if resp.status_code not in (200, 204):
            self._check_auth_error(resp)
            resp.raise_for_status()

    def get_messages(self, session_id: str, order: str = "asc", limit: int = 500) -> list[dict]:
        resp = self.session.get(
            self._url(f"/api/session/{session_id}/message"),
            params={"order": order, "limit": limit},
        )
        self._check_auth_error(resp)
        resp.raise_for_status()
        return resp.json()["data"]

    def list_models(self) -> list[dict]:
        resp = self.session.get(self._url("/api/model"))
        self._check_auth_error(resp)
        resp.raise_for_status()
        return resp.json()["data"]

    def event_stream(self):
        """Yields (event_name, raw_data_str) tuples from GET /api/event (SSE).
        Never raises out of the generator on transient errors — the caller
        (SSEWaker) treats any exception as "reconnect after a short pause".
        """
        with self.session.get(self._url("/api/event"), stream=True, timeout=None) as resp:
            self._check_auth_error(resp)
            resp.raise_for_status()
            event_name = None
            data_lines: list[str] = []
            for raw_line in resp.iter_lines(decode_unicode=True):
                if raw_line is None:
                    continue
                line = raw_line
                if line == "":
                    if data_lines:
                        yield (event_name, "\n".join(data_lines))
                    event_name, data_lines = None, []
                    continue
                if line.startswith("event:"):
                    event_name = line[len("event:"):].strip()
                elif line.startswith("data:"):
                    data_lines.append(line[len("data:"):].strip())
                # ignore "id:" and comment lines (":") — not needed here


# --------------------------------------------------------------------------
# Model catalog (for context-window sizing)
# --------------------------------------------------------------------------

class ModelCatalog:
    def __init__(self, client: OpenCodeClient):
        self.client = client
        self._by_provider_model: dict[tuple[str, str], int] = {}
        self._by_id: dict[str, int] = {}
        self._loaded = False

    def _load(self) -> None:
        try:
            for m in self.client.list_models():
                ctx = (m.get("limit") or {}).get("context")
                if not ctx:
                    continue
                self._by_provider_model[(m["providerID"], m["modelID"])] = ctx
                self._by_id[m["id"]] = ctx
        except requests.exceptions.RequestException:
            pass  # context-window display is best-effort
        self._loaded = True

    def context_limit(self, model_ref: dict | None) -> Optional[int]:
        if not model_ref:
            return None
        if not self._loaded:
            self._load()
        key = (model_ref.get("providerID"), model_ref.get("id"))
        if key in self._by_provider_model:
            return self._by_provider_model[key]
        return self._by_id.get(model_ref.get("id"))


# --------------------------------------------------------------------------
# Background "wake me on change" signal via SSE, with polling fallback
# --------------------------------------------------------------------------

class SSEWaker:
    def __init__(self, client: OpenCodeClient):
        self.client = client
        self._q: "queue.Queue[None]" = queue.Queue(maxsize=1)
        self._stop = threading.Event()
        self._thread = threading.Thread(target=self._run, daemon=True)

    def start(self) -> None:
        self._thread.start()

    def stop(self) -> None:
        self._stop.set()

    def _run(self) -> None:
        while not self._stop.is_set():
            try:
                for _event_name, _data in self.client.event_stream():
                    if self._stop.is_set():
                        return
                    self._nudge()
            except requests.exceptions.RequestException:
                pass
            if not self._stop.is_set():
                time.sleep(1.0)  # brief pause before reconnecting

    def _nudge(self) -> None:
        try:
            self._q.put_nowait(None)
        except queue.Full:
            pass

    def wait(self, timeout: float) -> bool:
        """Blocks until either an SSE event arrives or timeout elapses.
        Returns True if woken by an event, False on timeout (fallback poll)."""
        try:
            self._q.get(timeout=timeout)
            return True
        except queue.Empty:
            return False


