"""Conservative PDF chunk cleanup helpers for scientific RAG ingestion.

The cleaner repairs common extraction artifacts while preserving evidence-bearing
scientific text. It also exposes DOI normalization and quality-warning helpers
used by ingest.py.
"""

CONTROL_RE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")
ZERO_WIDTH_RE = re.compile(r"[\u200b-\u200f\u202a-\u202e\u2060\ufeff]")
PRIVATE_USE_RE = re.compile(r"/[Uu]ni[Ff][0-9A-Fa-f]{3,5}|[\ue000-\uf8ff]")
MULTISPACE_RE = re.compile(r"[ \t]{2,}")
MULTIBLANK_RE = re.compile(r"\n{3,}")
BROKEN_HYPHEN_RE = re.compile(r"(?<=[A-Za-z])[-\u2010-\u2015]\s*\n\s*(?=[a-z])")
SPACED_HYPHEN_RE = re.compile(r"(?<=[A-Za-z])\s+[-\u2010-\u2015]\s+(?=[A-Za-z])")
LINE_WRAP_RE = re.compile(r"(?<=[a-z,;:)])\n(?=[a-z(])")
SOFT_WRAP_RE = re.compile(r"(?<![.!?:;\n])\n(?!\s*[-*\u2022\d]+[.)]\s)(?=\S)")
DOI_SPACE_RE = re.compile(r"\b(10\.\d{4,9})\s*/\s*([^\s]+)", re.I)
DOI_LABEL_SPACE_RE = re.compile(r"\bdoi\s*[:：]\s*(10\.\d{4,9})\s*/\s*([^\s]+)", re.I)
URL_SPACE_RE = re.compile(r"\b(https?://|www\.)\s+", re.I)
URL_LINEBREAK_RE = re.compile(r"\b(https?://|www\.)\s*\n\s*", re.I)
DOI_URL_RE = re.compile(r"https?://(?:dx\.)?doi\.org/\s*", re.I)
FIGURE_SPACED_RE = re.compile(r"\b[fF]\s*[iI]\s*[gG]\s*[uU]\s*[rR]\s*[eE]\b")
TABLE_SPACED_RE = re.compile(r"\b[tT]\s*[aA]\s*[bB]\s*[lL]\s*[eE]\b")
REFERENCE_SPACED_RE = re.compile(r"\b[rR]\s*[eE]\s*[fF]\s*[eE]\s*[rR]\s*[eE]\s*[nN]\s*[cC]\s*[eE]\s*[sS]\b")
PIPE_EDGE_RE = re.compile(r"(?m)^\s*\|\s*|\s*\|\s*$")
DANGLING_PAGE_RE = re.compile(r"(?m)^\s*(?:Page\s*)?\d{1,4}\s*$")
REPEATED_PUNCT_RE = re.compile(r"([,.;:!?]){3,}")

UNICODE_REPLACEMENTS = {
    "\u00ad": "",
    "\u2212": "-",
    "\u2010": "-",
    "\u2011": "-",
    "\u2012": "-",
    "\u2013": "-",
    "\u2014": "-",
    "\u2018": "'",
    "\u2019": "'",
    "\u201c": '"',
    "\u201d": '"',
    "\u00a0": " ",
    "\uf0b7": "•",
}

MOJIBAKE_REPLACEMENTS = {
    "â€“": "-",
    "â€”": "-",
    "â€˜": "'",
    "â€™": "'",
    "â€œ": '"',
    "â€\x9d": '"',
    "Â ": " ",
    "ï¬\x81": "fi",
    "ï¬\x82": "fl",
}


def _safe_len(text: str) -> int:
    return max(len(text or ""), 1)


def _change_ratio(before: str, after: str) -> float:
    before_len = _safe_len(before)
    after_len = len(after or "")
    length_delta = abs(before_len - after_len) / before_len
    similarity = difflib.SequenceMatcher(a=before or "", b=after or "").ratio()
    return max(length_delta, 1.0 - similarity)


def _replace_many(text: str, replacements: dict[str, str]) -> str:
    for old, new in replacements.items():
        text = text.replace(old, new)
    return text


def _clean_lines(text: str) -> str:
    lines = []
    for raw in text.split("\n"):
        line = MULTISPACE_RE.sub(" ", raw).strip()
        if not line:
            lines.append("")
            continue
        lines.append(line)
    return "\n".join(lines)


def normalize_doi_candidate(value: Optional[str]) -> Optional[str]:
    if not value:
        return None
    value = html.unescape(str(value)).strip().rstrip(".,;)\"]")
    value = DOI_URL_RE.sub("", value)
    value = re.sub(r"^doi\s*[:：]\s*", "", value, flags=re.I)
    value = re.sub(r"\s+", "", value)
    match = DOI_PATTERN.search(value)
    if not match:
        return None
    doi = match.group(0).rstrip(".,;)\"]")
    return doi.lower()


def extract_dois(text: str) -> list[str]:
    if not text:
        return []
    fixed = _normalize_broken_doi_and_url(text)
    values = []
    for match in DOI_PATTERN.finditer(fixed):
        doi = normalize_doi_candidate(match.group(0))
        if doi and doi not in values:
            values.append(doi)
    return values


def _normalize_broken_doi_and_url(text: str) -> str:
    text = DOI_LABEL_SPACE_RE.sub(lambda m: f"doi:{m.group(1)}/{m.group(2)}", text)
    text = DOI_SPACE_RE.sub(lambda m: f"{m.group(1)}/{m.group(2)}", text)
    text = URL_LINEBREAK_RE.sub(lambda m: m.group(1), text)
    text = URL_SPACE_RE.sub(lambda m: m.group(1), text)
    text = DOI_URL_RE.sub("https://doi.org/", text)
    return text


def _unified_diff(before: str, after: str, context_lines: int = 3) -> str:
    return "\n".join(
        difflib.unified_diff(
            before.splitlines(),
            after.splitlines(),
            fromfile="before",
            tofile="after",
            lineterm="",
            n=context_lines,
        )
    )


def _append_major_change(
    report: Optional[dict[str, Any]],
    *,
    chunk_id: Optional[str],
    before: str,
    after: str,
    change_ratio: float,
    warn_threshold: float,
    context: Optional[dict[str, Any]] = None,
    diff_context_lines: int = 3,
    max_text_chars: int = 12000,
) -> None:
    if report is None:
        return
    key = chunk_id or f"unknown_{len(report) + 1}"
    before_trimmed = before[:max_text_chars]
    after_trimmed = after[:max_text_chars]
    report[key] = {
        "chunk_id": chunk_id,
        "change_ratio": round(change_ratio, 6),
        "warn_threshold": warn_threshold,
        "context": context or {},
        "before_char_count": len(before),
        "after_char_count": len(after),
        "before_truncated": len(before) > max_text_chars,
        "after_truncated": len(after) > max_text_chars,
        "before_excerpt": before_trimmed,
        "after_excerpt": after_trimmed,
        "diff": _unified_diff(before_trimmed, after_trimmed, context_lines=diff_context_lines),
    }


def write_major_change_report(report: dict[str, Any], output_path: str | Path, *, as_jsonl: bool = False) -> int:
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    records_by_id = dict(sorted(report.items(), key=lambda kv: kv[0]))
    if not as_jsonl:
        payload = {
            "created_at": datetime.now(timezone.utc).isoformat(),
            "record_count": len(records_by_id),
            "chunks": records_by_id,
        }
        path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    else:
        with path.open("w", encoding="utf-8") as f:
            for record in records_by_id.values():
                f.write(json.dumps(record, ensure_ascii=False) + "\n")
    return len(records_by_id)


def clean_good_chunk(
    text,
    warn_threshold=0.35,
    *,
    chunk_id=None,
    major_change_report=None,
    report_context=None,
    diff_context_lines=3,
    max_report_text_chars=12000,
):
    """Normalize an already-plausible RAG chunk without semantic pruning.

    This function intentionally does not delete scientific content based on
    meaning. It fixes encoding, line wrap, DOI/URL, and punctuation artifacts and
    records major destructive changes for audit.
    """
    if text is None:
        text = ""
    if not isinstance(text, str):
        text = str(text)

    original = text
    cleaned = html.unescape(text)
    cleaned = unicodedata.normalize("NFKC", cleaned)
    cleaned = _replace_many(cleaned, UNICODE_REPLACEMENTS)
    cleaned = _replace_many(cleaned, MOJIBAKE_REPLACEMENTS)
    cleaned = CONTROL_RE.sub("", cleaned)
    cleaned = ZERO_WIDTH_RE.sub("", cleaned)
    cleaned = PRIVATE_USE_RE.sub(" ", cleaned)

    cleaned = cleaned.replace("\r\n", "\n").replace("\r", "\n")
    cleaned = BROKEN_HYPHEN_RE.sub("", cleaned)
    cleaned = SPACED_HYPHEN_RE.sub("-", cleaned)
    cleaned = LINE_WRAP_RE.sub(" ", cleaned)
    cleaned = SOFT_WRAP_RE.sub(" ", cleaned)

    cleaned = _normalize_broken_doi_and_url(cleaned)
    cleaned = FIGURE_SPACED_RE.sub("Figure", cleaned)
    cleaned = TABLE_SPACED_RE.sub("Table", cleaned)
    cleaned = REFERENCE_SPACED_RE.sub("References", cleaned)

    if not is_structured_table_text(cleaned):
        cleaned = PIPE_EDGE_RE.sub("", cleaned)
    cleaned = DANGLING_PAGE_RE.sub("", cleaned)
    cleaned = _clean_lines(cleaned)
    cleaned = re.sub(r"\s+([,.;:!?%)\]])", r"\1", cleaned)
    cleaned = re.sub(r"([(\[])\s+", r"\1", cleaned)
    cleaned = re.sub(r"\bdoi\s*:\s*", "doi:", cleaned, flags=re.I)
    cleaned = REPEATED_PUNCT_RE.sub(r"\1", cleaned)
    cleaned = MULTIBLANK_RE.sub("\n\n", cleaned).strip()

    ratio = _change_ratio(original, cleaned)
    if ratio >= warn_threshold:
        _append_major_change(
            major_change_report,
            chunk_id=chunk_id,
            before=original,
            after=cleaned,
            change_ratio=ratio,
            warn_threshold=warn_threshold,
            context=report_context,
            diff_context_lines=diff_context_lines,
            max_text_chars=max_report_text_chars,
        )
        id_msg = f" for chunk_id={chunk_id}" if chunk_id else " for unknown chunk_id"
        warnings.warn(
            "clean_good_chunk substantially altered text{} ({:.0%} length change); "
            "review major_change_report for possible over-pruning.".format(id_msg, ratio),
            RuntimeWarning,
            stacklevel=2,
        )
    return cleaned

