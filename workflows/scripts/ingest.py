def token_count(text: str) -> int:
    return len(TOKEN_RE.findall(text or ""))


def sentence_count(text: str) -> int:
    return len(SENTENCE_RE.findall(text or ""))


def is_incomplete_end(text: str) -> bool:
    text = (text or "").strip()
    if not text:
        return True
    if TERMINAL_RE.search(text):
        return False
    if CAPTION_RE.search(text) and token_count(text) >= 50:
        return False
    if EQUATION_HINT_RE.search(text) and token_count(text) < 80:
        return False
    return True


def starts_lowercase(text: str) -> bool:
    return bool(LOWERCASE_START_RE.match((text or "").strip()))


def get_quality_flags(text: str, content_type: str, headings: list[str]) -> list[str]:
    flags: list[str] = []
    n_tokens = token_count(text)
    n_sentences = sentence_count(text)
    if n_tokens < 45:
        flags.append("short_chunk")
    if n_tokens > 450:
        flags.append("long_chunk")
    if starts_lowercase(text):
        flags.append("starts_lowercase")
    if is_incomplete_end(text):
        flags.append("ends_incomplete")
    if n_sentences == 0 and content_type not in {"equation", "table"}:
        flags.append("no_complete_sentence")
    if content_type == "table" and "is_structured_table_text" in globals() and is_structured_table_text(text):
        flags.append("structured_table")
    if LONG_TOKEN_RE.search(text):
        flags.append("long_token")
    if content_type == "table" and "|" not in text and n_sentences < 2:
        flags.append("flattened_table_fragment")
    if any(REFERENCE_HEADING_RE.fullmatch(h.strip()) for h in headings):
        flags.append("reference_section")
    if text.count("\n") > 10 and n_tokens < 120:
        flags.append("layout_fragment")
    return flags


def score_rag_fitness(text: str, content_type: str, flags: list[str]) -> float:
    n_tokens = token_count(text)
    score = 1.0
    if n_tokens < 35:
        score -= 0.25
    elif n_tokens < 60:
        score -= 0.10
    if n_tokens > 420:
        score -= 0.20
    elif n_tokens > 360:
        score -= 0.10

    penalties = {
        "starts_lowercase": 0.10,
        "ends_incomplete": 0.15,
        "no_complete_sentence": 0.16,
        "long_token": 0.12,
        "flattened_table_fragment": 0.12,
        "reference_section": 0.35,
        "layout_fragment": 0.10,
        "structured_table": -0.03,
    }
    for flag in flags:
        score -= penalties.get(flag, 0.05)

    if content_type in {"caption", "equation", "table"} and n_tokens >= 40:
        score += 0.05
    if SCIENCE_SIGNAL_RE.search(text or "") and n_tokens >= 45:
        score += 0.05
    return round(max(0.0, min(1.0, score)), 3)


def classify_content_type(text: str, headings: list[str]) -> str:
    stripped = (text or "").strip()
    lower_headings = " ".join(headings).lower()
    if any(REFERENCE_HEADING_RE.fullmatch(h.strip()) for h in headings):
        return "reference"
    if "is_structured_table_text" in globals() and is_structured_table_text(stripped):
        return "table"
    if "|" in stripped or (TABLE_HINT_RE.search(stripped) and stripped.count("\n") >= 3):
        return "table"
    if CAPTION_RE.search(stripped):
        return "caption"
    if "abstract" in lower_headings:
        return "abstract"
    if EQUATION_HINT_RE.search(stripped) and sentence_count(stripped) <= 1:
        return "equation"
    return "main_text"


def _dedupe_sorted(values: Iterable[Any]) -> list[Any]:
    seen = set()
    out = []
    for value in values:
        if value in (None, ""):
            continue
        key = str(value)
        if key not in seen:
            out.append(value)
            seen.add(key)
    try:
        return sorted(out)
    except TypeError:
        return out


def _get_headings(chunk: Any) -> list[str]:
    candidates = [
        getattr(chunk, "headings", None),
        getattr(getattr(chunk, "meta", None), "headings", None),
        getattr(getattr(chunk, "meta", None), "headings_chain", None),
    ]
    for value in candidates:
        if value:
            if isinstance(value, str):
                return [value]
            return [str(x) for x in value if str(x).strip()]
    return []


def _get_page_numbers(chunk: Any) -> list[int]:
    pages: list[int] = []
    meta = getattr(chunk, "meta", None)
    candidates = [
        getattr(chunk, "page_numbers", None),
        getattr(meta, "page_numbers", None),
        getattr(meta, "pages", None),
        getattr(meta, "doc_items", None),
    ]
    for value in candidates:
        if not value:
            continue
        items = value if isinstance(value, (list, tuple, set)) else [value]
        for item in items:
            if isinstance(item, int):
                pages.append(item)
                continue
            page_no = getattr(item, "page_no", None) or getattr(item, "page_number", None)
            if page_no is not None:
                try:
                    pages.append(int(page_no))
                except Exception:
                    pass
            prov = getattr(item, "prov", None)
            if prov:
                for p in prov if isinstance(prov, (list, tuple)) else [prov]:
                    page_no = getattr(p, "page_no", None) or getattr(p, "page_number", None)
                    if page_no is not None:
                        try:
                            pages.append(int(page_no))
                        except Exception:
                            pass
    return _dedupe_sorted(pages)


def _safe_doc_export_text(result: Any) -> str:
    doc = getattr(result, "document", result)
    for name in ("export_to_markdown", "export_to_text"):
        fn = getattr(doc, name, None)
        if callable(fn):
            try:
                return str(fn())
            except Exception:
                continue
    return str(doc)


