def run_pipeline(args: argparse.Namespace):
    pdf_folder = Path(args.pdf_folder)
    md_folder = Path(args.md_folder)
    txt_folder = Path(args.txt_folder)
    log_folder = Path(args.log_folder) if args.log_folder else None
    for folder in (
        md_folder,
        txt_folder,
        Path(args.output_jsonl).parent,
        Path(args.quarantined_jsonl).parent,
        Path(args.qa_report).parent,
        Path(args.major_change_report).parent,
        *( [log_folder] if log_folder else [] ),
    ):
        folder.mkdir(parents=True, exist_ok=True)
    execution_log: list[dict[str, Any]] = []

    converter = build_converter()
    chunker = HybridChunker()
    major_change_report: dict[str, Any] = {}
    qa: dict[str, Any] = {
        "created_at": utc_now(),
        "pipeline_id": PIPELINE_ID,
        "downstream_ingestion_strategies": DOWNSTREAM_INGESTION_STRATEGIES,
        "parameters": vars(args),
        "documents": {},
        "totals": {
            "documents_processed": 0,
            "documents_failed": 0,
            "original_chunks": 0,
            "kept_chunks": 0,
            "quarantined_chunks": 0,
            "quality_flags": Counter(),
            "content_types": Counter(),
            "quarantine_reasons": Counter(),
            "ingestion_strategies": Counter(),
            "rag_fitness_scores": [],
        },
    }

    pdf_paths = iter_pdf_paths(pdf_folder, args.pdf_glob)
    if args.limit:
        pdf_paths = pdf_paths[: args.limit]

    logging.getLogger("transformers.tokenization_utils_base").setLevel(logging.ERROR)

    with open(args.output_jsonl, "w", encoding="utf-8") as kept_out, open(args.quarantined_jsonl, "w", encoding="utf-8") as quarantine_out:
        for pdf_path in pdf_paths:
            original_n_chunks = 0
            kept_rows: list[dict[str, Any]] = []
            quarantine_rows: list[dict[str, Any]] = []
            source_info = source_strategy_for(pdf_folder, pdf_path)
            try:
                print(f"Processing {pdf_path}...")
                result = converter.convert(pdf_path)
                doc_text = _safe_doc_export_text(result)
                document = getattr(result, "document", result)
                chunks = list(chunker.chunk(dl_doc=document))
                original_n_chunks = len(chunks)

                front_matter = "\n".join(_chunk_text(chunk) for chunk in chunks[:10])
                dois = extract_dois(front_matter)
                doi = normalize_doi_candidate(dois[0]) if dois else None

                document_metadata = {} if args.no_crossref else lookup_crossref_metadata(doi, mailto=args.crossref_mailto)
                def get_authors():
                    authors = document_metadata.get("meta", {}).get("document_metadata", {}).get("author", [])
                    return [" ".join(filter(None, [a.get("given"), a.get("family")])) for a in authors]
                
                output_front_matter = (
                    "---\n"
                    f"Title: {document_metadata.get("title", "")}\n"
                    f"DOI: {doi}\n"
                    f"Authors: {get_authors()}\n"
                    f"Published On: {"-".join(document_metadata.get("issued", {}).get("date_parts", [[]])[0])}\n"
                    f"Journal: {document_metadata.get("container_title", "")}\n"
                    "---\n"
                )

                (md_folder / f"{pdf_path.stem}.md").write_text(output_front_matter)
                append_text((md_folder / f"{pdf_path.stem}.md"), doc_text)

                candidate_rows = []
                for i, chunk in enumerate(chunks):
                    chunk_id = f"{pdf_path.stem}_chunk_{i}"
                    raw_text = str(getattr(chunk, "text", "") or "")
                    headings = _get_headings(chunk)
                    page_numbers = _get_page_numbers(chunk)
                    cleaned = clean_good_chunk(
                        raw_text,
                        chunk_id=chunk_id,
                        major_change_report=major_change_report,
                        report_context={"document_name": pdf_path.name, "page_numbers": page_numbers, "headings": headings, "pipeline_id": PIPELINE_ID, "ingestion_strategy": source_info.get("ingestion_strategy")},
                    )
                    cleaned = normalize_table_block(cleaned)
                    row = make_row(pdf_path=pdf_path, chunk=chunk, chunk_id=chunk_id, text=cleaned, doi=doi, document_metadata=document_metadata, source_info=source_info)
                    candidate_rows.append(row)

                kept_rows, quarantine_rows = postprocess_rows(candidate_rows, min_merge_tokens=args.min_merge_tokens, max_merge_tokens=args.max_merge_tokens, enable_boundary_repair=not args.disable_boundary_repair)

                for row in kept_rows:
                    kept_out.write(json.dumps(row, ensure_ascii=False) + "\n")
                for row in quarantine_rows:
                    quarantine_out.write(json.dumps(row, ensure_ascii=False) + "\n")

                (txt_folder / f"{pdf_path.stem}.txt").write_text(output_front_matter)
                append_text((txt_folder / f"{pdf_path.stem}.txt"), ("\n\n".join(row["text"] for row in kept_rows)))
                update_qa(qa, pdf_name=pdf_path.name, original=original_n_chunks, kept=kept_rows, quarantine=quarantine_rows, source_info=source_info)
                message = f"kept={len(kept_rows)} quarantined={len(quarantine_rows)} original={original_n_chunks}"
                print(f"  {message}")
                execution_log.append({
                    "timestamp": utc_now(),
                    "level": "info",
                    "document": pdf_path.name,
                    "message": message,
                    "ingestion_strategy": source_info.get("ingestion_strategy"),
                })
                time.sleep(0.05)

            except Exception as exc:
                error = str(exc)
                print(f"Error processing {pdf_path.name}: {error}")
                execution_log.append({
                    "timestamp": utc_now(),
                    "level": "error",
                    "document": pdf_path.name,
                    "message": error,
                    "ingestion_strategy": source_info.get("ingestion_strategy"),
                })
                update_qa(qa, pdf_name=pdf_path.name, original=original_n_chunks, kept=kept_rows, quarantine=quarantine_rows, source_info=source_info, error=error)

    major_count = write_major_change_report(major_change_report, args.major_change_report)
    qa = finalize_qa(qa, major_count)
    Path(args.qa_report).write_text(json.dumps(qa, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Extraction complete. Kept chunks: {args.output_jsonl}")
    print(f"Quarantine stream: {args.quarantined_jsonl}")
    print(f"QA report: {args.qa_report}")
    print(f"Major change report: {args.major_change_report} ({major_count} entries)")
    if log_folder:
        log_record = {
            "created_at": utc_now(),
            "pipeline_id": PIPELINE_ID,
            "parameters": vars(args),
            "summary": {
                "kept_jsonl": args.output_jsonl,
                "quarantined_jsonl": args.quarantined_jsonl,
                "qa_report": args.qa_report,
                "major_change_report": args.major_change_report,
                "major_change_entries": major_count,
            },
            "events": execution_log,
        }
        (log_folder / "pdf_to_jsonl_execution_log.json").write_text(
            json.dumps(log_record, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )

