#!/usr/bin/env python3

"""
---
Generated by Claude.ai Sonnet 5 (Medium effort)
---

Run a prompt against a locally running OpenCode 2 server (HttpApi v2), with a
specific agent, skill, and provider/model — and get live visibility into what
the agent is doing: thinking (reasoning), tool calls, skill use, sub-agent
invocations, and token / context-window usage.

Requires OpenCode 2 running locally, e.g.:

    opencode2 serve --port 4096

Docs: https://opencode.ai/v2/docs/api

CLI usage:
    python opencode_run.py \
        --prompt "Refactor this function for clarity" \
        --agent build \
        --skill code-review \
        --provider anthropic \
        --model claude-sonnet-5 \
        --directory /path/to/your/project

Add --quiet to suppress live output and just print the final answer.
Add --log-file PATH to send live output to a file instead of stdout.

Library usage:
    from opencode_run import chat, Event
    import argparse

    def on_event(event: Event) -> None:
        ...  # forward to LangSmith, structured logging, whatever you like

    args = argparse.Namespace(base_url=..., agent="build", prompt="...", ...)
    reply = chat(args, on_event=on_event)

--- Architecture ---

Nothing in this module prints directly. Everything that happens during a
run — thinking deltas, tool-call transitions, skill activation, sub-agent
discovery, token/cost/context updates, the final answer — is emitted as an
`Event` to a single `on_event` callback. This keeps the client itself
un-opinionated about where output goes; `make_stream_listener()` and
`file_listener()` are just two simple reference listeners (stdout / file)
built on top of that same callback contract. Anything else — LangSmith,
OpenTelemetry, structured JSON logging — is just a different `on_event`
implementation, written outside this file.

Each Event carries a `key` (a unique id for the "span" it belongs to,
e.g. a specific tool call or thinking block) and a `parent_key` (the key
of the span it's logically nested under). Sub-agent sessions inherit the
key of the "task" tool call that spawned them as their `parent_key`, so a
listener can reconstruct proper nesting (e.g. LangSmith parent/child runs)
without relying on the numeric `depth` field, which only tells you how
deep something is, not which sibling span it belongs under.

--- Design notes / known assumptions ---

The v2 HttpApi is marked "experimental" and its SSE event payload shape
(GET /api/event) isn't documented beyond the outer envelope
{id, event, data}. Rather than depend on parsing that payload precisely,
this script uses the event stream only as a low-latency "something
changed, go re-sync" signal (falling back to polling on a fixed interval
regardless, so it degrades gracefully if SSE payload parsing ever fails
or the stream drops). Rendering is always driven by re-reading
GET /api/session/{id} and GET /api/session/{id}/message, so what you see
is always ground truth from the API, just possibly ~1 poll-interval late
if SSE didn't wake us early.

Sub-agent discovery: the model invokes sub-agents via a "task" tool.
There is no documented field linking a task-tool call directly to the
child session it spawns, so this script infers it heuristically: after a
"task" tool call appears, it lists all sessions and claims the newest
not-yet-claimed session whose parentID matches the current session. This
works well for the common case of sequential sub-agent calls; if an agent
fires many sub-agents in tight parallel, attribution to the *correct*
task call may be approximate (though every child session is still found
and rendered).
"""

