def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Run a prompt on a local OpenCode server with live visibility")
    parser.add_argument("--base-url", default=os.environ.get("OPENCODE_URL", DEFAULT_BASE_URL),
                         help="Base URL of the running opencode server (default: http://localhost:4096)")
    parser.add_argument("--username", default=None,
                         help="Basic auth username (default: 'opencode', or $OPENCODE_SERVER_USERNAME)")
    parser.add_argument("--password", default=None,
                         help="Basic auth password (default: $OPENCODE_PASSWORD / $OPENCODE_SERVER_PASSWORD). "
                              "Required if the server was started without an explicit password, since opencode2 "
                              "then generates a random one and prints it to its own console at startup.")
    parser.add_argument("--directory", default=os.getcwd(),
                         help="Project directory the session should be scoped to (default: cwd)")
    parser.add_argument("--agent", required=True, help="Agent name to use for the session, e.g. 'build' or 'plan'")
    parser.add_argument("--skill", default=None, help="Skill name to activate before prompting (optional)")
    parser.add_argument("--provider", default=None, help="Provider ID to use, e.g. 'anthropic' (requires --model)")
    parser.add_argument("--model", default=None, help="Model ID to use, e.g. 'claude-sonnet-5' (requires --provider)")
    parser.add_argument("--variant", default=None, help="Optional model variant")
    parser.add_argument("--prompt", required=True, help="The prompt text to send")
    parser.add_argument("--title", default=None, help="Optional session title")
    parser.add_argument("--timeout", type=float, default=600.0, help="Max seconds to wait for a reply")
    parser.add_argument("--quiet", action="store_true", help="Suppress live output; print only the final answer")
    parser.add_argument("--log-file", default=None,
                         help="Write live output here instead of stdout (ignored if --quiet)")
    return parser


def main():
    parser = build_arg_parser()
    args = parser.parse_args()

    try:
        reply = chat(args)
    except ValueError as e:
        parser.error(str(e))
        return
    except RuntimeError as e:
        print(str(e), file=sys.stderr)
        sys.exit(1)
    except requests.exceptions.RequestException as e:
        print(f"Could not reach OpenCode server at {args.base_url}: {e}", file=sys.stderr)
        sys.exit(1)

    # This is the program's actual result, not a log line, so it's printed
    # directly regardless of --quiet/--log-file (which only affect the live
    # Event stream produced while the run is in progress).
    print(reply if reply else "(no text content returned)")


if __name__ == "__main__":
    main()